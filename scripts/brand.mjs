// Builds the app's logo assets from the originals in brand/: the inline Logo
// component, the favicon and the iOS home screen icon. Usage: node scripts/brand.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { chromium } from 'playwright-core'

const BLUE = '#2848D8'
const BLUE_ON_DARK = '#8EA7FF'
const root = new URL('../', import.meta.url)
const source = readFileSync(new URL('brand/inktap-horizontal-color.svg', root), 'utf8')

// Integer coordinates are well under a tenth of a pixel at any size the app uses.
const round = (d) => d.replace(/-?\d*\.\d+/g, (n) => String(Math.round(Number(n))))
const part = (name) => {
  const block = source.match(new RegExp(`<g data-part="${name}"([^>]*)>\\s*<svg([^>]*)>([\\s\\S]*?)</svg>\\s*</g>`))
  if (!block) throw new Error(`brand/inktap-horizontal-color.svg has no ${name} part`)
  const attr = (a) => block[2].match(new RegExp(`\\b${a}="([^"]+)"`))?.[1]
  return {
    transform: block[1].match(/transform="([^"]+)"/)?.[1],
    box: { x: attr('x') ?? '0', y: attr('y') ?? '0', width: attr('width'), height: attr('height'), viewBox: attr('viewBox') },
    paths: [...block[3].matchAll(/\bd="([^"]+)"/g)].map((m) => round(m[1])),
  }
}
const symbol = part('symbol')
const name = part('name')

const browser = await chromium.launch({ channel: 'chrome' })
const page = await browser.newPage()
await page.setContent(`<body style="margin:0">${source}</body>`)
const measured = await page.evaluate(() => {
  const outer = document.querySelector('svg').getBoundingClientRect()
  let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity
  for (const p of document.querySelectorAll('path')) {
    const r = p.getBoundingClientRect()
    x0 = Math.min(x0, r.left - outer.left)
    y0 = Math.min(y0, r.top - outer.top)
    x1 = Math.max(x1, r.right - outer.left)
    y1 = Math.max(y1, r.bottom - outer.top)
  }
  let s0 = Infinity, t0 = Infinity, s1 = -Infinity, t1 = -Infinity
  for (const p of document.querySelectorAll('[data-part="symbol"] path')) {
    const r = p.getBoundingClientRect()
    s0 = Math.min(s0, r.left - outer.left)
    t0 = Math.min(t0, r.top - outer.top)
    s1 = Math.max(s1, r.right - outer.left)
    t1 = Math.max(t1, r.bottom - outer.top)
  }
  const mark = [...document.querySelectorAll('[data-part="symbol"] path')].map((p) => p.getBBox())
  const mx0 = Math.min(...mark.map((b) => b.x))
  const my0 = Math.min(...mark.map((b) => b.y))
  const mx1 = Math.max(...mark.map((b) => b.x + b.width))
  const my1 = Math.max(...mark.map((b) => b.y + b.height))
  return { logo: [x0, y0, x1 - x0, y1 - y0], markOnly: [s0, t0, s1 - s0, t1 - t0], mark: [mx0, my0, mx1 - mx0, my1 - my0] }
})

const fix = (n) => Math.round(n * 10) / 10
const logoBox = measured.logo.map(fix).join(' ')
const markBox = measured.markOnly.map(fix).join(' ')
const nested = (p, indent) =>
  `${indent}<svg x="${p.box.x}" y="${p.box.y}" width="${p.box.width}" height="${p.box.height}" viewBox="${p.box.viewBox}">\n` +
  p.paths.map((d) => `${indent}  <path fill="currentColor" d="${d}" />`).join('\n') +
  `\n${indent}</svg>`

writeFileSync(
  new URL('src/ui/Logo.tsx', root),
  `// Generated by scripts/brand.mjs from brand/inktap-horizontal-color.svg; edit the source and rerun.
// The mark and the name take their colors from --logo-mark and --logo-name;
// variant="mark" draws the symbol alone, for tight spaces.
export function Logo({ className = '', label = 'InkTap', variant = 'full' }: { className?: string; label?: string | null; variant?: 'full' | 'mark' }) {
  const markOnly = variant === 'mark'
  return (
    <svg
      className={\`logo \${className}\`}
      viewBox={markOnly ? '${markBox}' : '${logoBox}'}
      role={label ? 'img' : undefined}
      aria-label={label ?? undefined}
      aria-hidden={label ? undefined : true}
      focusable="false"
    >
      <g className="logo__mark" transform="${symbol.transform}">
${nested(symbol, '        ')}
      </g>
      {markOnly ? null : (
        <g className="logo__name">
${nested(name, '          ')}
        </g>
      )}
    </svg>
  )
}
`,
)

// A square around the mark with a little air, so it reads at 16px.
const [mx, my, mw, mh] = measured.mark
const side = Math.max(mw, mh) * 1.08
const square = [mx + mw / 2 - side / 2, my + mh / 2 - side / 2, side, side].map((n) => Math.round(n)).join(' ')
const markPaths = symbol.paths.map((d) => `<path d="${d}"/>`).join('')
writeFileSync(
  new URL('public/favicon.svg', root),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${square}"><style>path{fill:${BLUE}}@media (prefers-color-scheme:dark){path{fill:${BLUE_ON_DARK}}}</style>${markPaths}</svg>\n`,
)

// iOS rounds the corners itself, so the tile is a full-bleed square.
const tileSide = Math.max(mw, mh) / 0.62
const tile = [mx + mw / 2 - tileSide / 2, my + mh / 2 - tileSide / 2, tileSide, tileSide].map((n) => Math.round(n))
await page.setViewportSize({ width: 180, height: 180 })
await page.setContent(
  `<body style="margin:0"><svg xmlns="http://www.w3.org/2000/svg" width="180" height="180" viewBox="${tile.join(' ')}"><rect x="${tile[0]}" y="${tile[1]}" width="${tile[2]}" height="${tile[3]}" fill="${BLUE}"/><g fill="#FFFFFF">${markPaths}</g></svg></body>`,
)
await page.screenshot({ path: new URL('public/apple-touch-icon.png', root).pathname.replace(/^\/([A-Z]:)/, '$1'), clip: { x: 0, y: 0, width: 180, height: 180 } })
await browser.close()
console.log(`logo viewBox ${logoBox}; mark ${measured.mark.map(fix).join(' ')}; favicon ${square}`)
